MASS = 8.7
MU_LO = 0.30
MU_HI = 0.50
WLL = 3.15


def comma(value, digits=1):
    return f"{value:.{digits}f}".replace(".", ",")


def forces():
    length = branch_len()
    dx = FACE - EYE_X
    dz = EYE_SIDE[1] - HITCH_Z
    pull_lo = MASS * MU_LO
    pull_hi = MASS * MU_HI
    # В текст берут 2,6 и 4,4 тс — те же округления, что на схеме.
    pull_lo_r = 2.6
    pull_hi_r = 4.4
    tension = (pull_hi_r / 2.0) * (length / dx)
    tension_lo = (pull_lo_r / 2.0) * (length / dx)
    lift = 2.0 * tension * (dz / length)
    eye = math.hypot(pull_hi_r, lift)
    eye_lo = eye * (pull_lo_r / pull_hi_r)
    rail_clear = AXIS_GAP / 2 - GAUGE / 2 - MACHINE_W / 2
    angle = math.degrees(math.asin(dz / length))
    return {
        "length": length,
        "dx": dx,
        "dy": HITCH,
        "dz": dz,
        "pull_lo": pull_lo,
        "pull_hi": pull_hi,
        "tension": tension,
        "tension_lo": tension_lo,
        "lift": lift,
        "eye": eye,
        "eye_lo": eye_lo,
        "rail_clear": rail_clear,
        "angle": angle,
        "reach": 12.50 - 7.55,
    }


class Sheet:
    def __init__(self, pdf):
        self.pdf = pdf
        self.fig = None
        self.y = 0.0
        self.page = 0
        self.left = 0.07
        self.right = 0.93
        self.top = 0.94
        self.bottom = 0.06
        self.width = 8.27
        self.height = 11.69

    def new_page(self):
        if self.fig is not None:
            self.pdf.savefig(self.fig)
            plt.close(self.fig)
        self.page += 1
        self.fig = plt.figure(figsize=(self.width, self.height), dpi=120, facecolor="white")
        self.y = self.top
        self.fig.text(
            0.93, 0.025, str(self.page), ha="right", va="bottom",
            fontsize=9, fontproperties=SANS, color=INK,
        )

    def _dy(self, size):
        return (size / 72 * 1.42) / self.height

    def _need(self, frac):
        if self.y - frac < self.bottom:
            self.new_page()

    def gap(self, inches):
        frac = inches / self.height
        self._need(frac)
        self.y -= frac

    def line(self, text, size=11, bold=False, indent=0.0, gap_after=0.0, mono=False):
        dy = self._dy(size) + gap_after / self.height
        self._need(dy)
        face = MONO if mono else (BOLD if bold else SANS)
        self.fig.text(
            self.left + indent, self.y, text, ha="left", va="top",
            fontsize=size, fontproperties=face, color=INK,
        )
        self.y -= dy

    def paragraph(self, text, size=11, indent=0.0, width=74):
        parts = textwrap.wrap(text, width=width)
        need = len(parts) * self._dy(size) + 0.012
        if need < 0.45 and self.y - need < self.bottom:
            self.new_page()
        for part in parts:
            self.line(part, size=size, indent=indent)
        self.y -= 0.012

    def bullet(self, text, width=70):
        rows = textwrap.wrap(text, width=width)
        for i, part in enumerate(rows):
            mark = "–  " if i == 0 else "    "
            self.line(mark + part, size=11, indent=0.015)
        self.y -= 0.006

    def close(self):
        if self.fig is not None:
            self.pdf.savefig(self.fig)
            plt.close(self.fig)


